import { z } from 'zod';
import type { RouteDef } from '../types';
import {
  computeSha256,
  parseEmail,
  parsePlainText,
  buildEvidencePath,
  type IngestionResult,
  type SourceType,
} from '../../ingestion';

export const UploadEvidenceInputSchema = z.object({
  sourceType: z.enum(['EMAIL', 'DOCUMENT', 'SCREENSHOT', 'MANUAL_LOG']),
  filename: z.string().min(1).max(255),
  mimeType: z.string().min(1).max(128),
  content: z.string(), // base64 or raw string content
  isBase64: z.boolean().default(false),
}).strict();

export const evidenceRoutes: RouteDef[] = [
  // List evidence items for a case
  {
    method: 'GET',
    pattern: '/cases/:id/evidence',
    auth: 'user',
    handler: async ({ user, db, params }) => {
      // Check ownership
      const { data: caseRow } = await db
        .from('cases')
        .select('id')
        .eq('id', params.id)
        .eq('owner_id', user.id)
        .single();

      if (!caseRow) {
        return new Response(
          JSON.stringify({ error: { code: 'NOT_FOUND', message: `Case ${params.id} not found` } }),
          { status: 404, headers: { 'Content-Type': 'application/json' } }
        );
      }

      const { data, error } = await db
        .from('evidence_items')
        .select(`
          id, display_id, source_type, original_filename, mime_type, size_bytes,
          storage_path, sha256, captured_at, uploaded_at, processing_status, deleted_at
        `)
        .eq('case_id', params.id)
        .order('uploaded_at', { ascending: false });

      if (error) {
        throw new Error(`Database error listing evidence: ${error.message}`);
      }

      return { evidence: data || [] };
    },
  },

  // Upload and ingest new evidence item
  {
    method: 'POST',
    pattern: '/cases/:id/evidence',
    auth: 'user',
    input: UploadEvidenceInputSchema,
    handler: async ({ user, db, admin, params, req }) => {
      // 1. Verify case ownership
      const { data: caseRow } = await db
        .from('cases')
        .select('id')
        .eq('id', params.id)
        .eq('owner_id', user.id)
        .single();

      if (!caseRow) {
        return new Response(
          JSON.stringify({ error: { code: 'NOT_FOUND', message: `Case ${params.id} not found` } }),
          { status: 404, headers: { 'Content-Type': 'application/json' } }
        );
      }

      const body = await req.json();
      const input = UploadEvidenceInputSchema.parse(body);

      // 2. Decode raw buffer
      const rawBuffer = input.isBase64
        ? Buffer.from(input.content, 'base64')
        : Buffer.from(input.content, 'utf8');

      // 3. Run Ingestion Pipeline (Phase 1)
      let ingestion: IngestionResult;
      if (input.sourceType === 'EMAIL' || input.mimeType === 'message/rfc822' || input.filename.endsWith('.eml')) {
        ingestion = await parseEmail(rawBuffer);
      } else if (input.mimeType === 'application/pdf' || input.filename.endsWith('.pdf')) {
        const { parsePdf } = await import('../../ingestion/pdf');
        ingestion = await parsePdf(rawBuffer);
      } else {
        ingestion = parsePlainText(rawBuffer, input.sourceType, input.mimeType);
      }

      // Generate evidence item UUID
      const evidenceId = crypto.randomUUID();
      const storagePath = buildEvidencePath(params.id, evidenceId);

      // 4. Store raw binary in private Supabase Storage
      let storageUploadAttempted = false;
      let evidenceInsertAttempted = false;
      let evidenceRow: {
        id: string;
        case_id: string;
        display_id: string;
        source_type: string;
        sha256: string;
        size_bytes: number;
        processing_status: string;
      };
      try {
        storageUploadAttempted = true;
        const { error: storageError } = await admin.storage
          .from('evidence')
          .upload(storagePath, rawBuffer, {
            contentType: input.mimeType,
            upsert: false,
          });

        if (storageError) {
          throw new Error(`Storage upload failed: ${storageError.message}`);
        }

        // 5. Insert EvidenceItem into DB (display_id generated by DB trigger)
        evidenceInsertAttempted = true;
        const { data, error: itemError } = await admin
          .from('evidence_items')
          .insert({
            id: evidenceId,
            case_id: params.id,
            source_type: ingestion.sourceType,
            original_filename: input.filename,
            mime_type: ingestion.mimeType,
            size_bytes: ingestion.sizeBytes,
            storage_path: storagePath,
            sha256: ingestion.sha256,
            captured_at: ingestion.capturedAt,
            processing_status: 'PROCESSED',
          })
          .select()
          .single();

        if (itemError || !data) {
          throw new Error(`Failed to insert evidence item: ${itemError?.message ?? 'No row returned'}`);
        }
        evidenceRow = data;

        // 6. Insert artifacts and all segments; any failed write aborts the upload.
        let normalizedArtifactId: string | undefined;
        for (const art of ingestion.artifacts) {
          const { data: artRow, error: artError } = await admin
            .from('evidence_artifacts')
            .insert({
              evidence_id: evidenceRow.id,
              artifact_type: art.artifactType,
              extraction_method: art.extractionMethod,
              version: art.version,
              raw_content: art.rawContent,
              created_by_process: art.createdByProcess,
            })
            .select('id')
            .single();

          if (artError || !artRow) {
            throw new Error(`Failed to insert evidence artifact: ${artError?.message ?? 'No row returned'}`);
          }
          if (art.artifactType === 'NORMALIZED_TEXT') normalizedArtifactId = artRow.id;
        }

        if (ingestion.segments.length > 0) {
          if (!normalizedArtifactId) {
            throw new Error('Cannot persist evidence segments without a normalized text artifact');
          }
          const { error: segmentError } = await admin.from('evidence_segments').insert(
            ingestion.segments.map((seg) => ({
              evidence_id: evidenceRow.id,
              artifact_id: normalizedArtifactId,
              ordinal: seg.ordinal,
              locator_type: seg.locatorType,
              locator: seg.locator,
              segment_text: seg.segmentText,
            }))
          );
          if (segmentError) {
            throw new Error(`Failed to insert evidence segments: ${segmentError.message}`);
          }
        }

        // 7. Audit log write
        const { error: auditError } = await admin.from('audit_events').insert({
          case_id: params.id,
          actor_type: 'USER',
          actor_id: user.id,
          entity_type: 'EVIDENCE',
          entity_id: evidenceRow.id,
          action: 'EVIDENCE_UPLOADED',
          metadata: {
            displayId: evidenceRow.display_id,
            sha256: evidenceRow.sha256,
            sizeBytes: evidenceRow.size_bytes,
            segmentCount: ingestion.segments.length,
          },
        });
        if (auditError) {
          throw new Error(`Failed to record evidence upload audit event: ${auditError.message}`);
        }
      } catch (error) {
        const cleanupErrors: string[] = [];
        if (evidenceInsertAttempted) {
          const { error: deleteError } = await admin
            .from('evidence_items')
            .delete()
            .eq('id', evidenceId);
          if (deleteError) cleanupErrors.push(deleteError.message);
        }
        if (storageUploadAttempted) {
          const { error: removeError } = await admin.storage
            .from('evidence')
            .remove([storagePath]);
          if (removeError) cleanupErrors.push(removeError.message);
        }
        if (cleanupErrors.length > 0) {
          throw new Error(
            `Evidence upload failed and cleanup was incomplete: ${cleanupErrors.join('; ')}`
          );
        }
        throw error;
      }

      return {
        id: evidenceRow.id,
        displayId: evidenceRow.display_id,
        caseId: evidenceRow.case_id,
        sourceType: evidenceRow.source_type,
        sha256: evidenceRow.sha256,
        sizeBytes: evidenceRow.size_bytes,
        processingStatus: evidenceRow.processing_status,
        segmentCount: ingestion.segments.length,
        segments: ingestion.segments,
      };
    },
  },

  // Get single evidence item with artifacts and segments (writes EVIDENCE_VIEWED)
  {
    method: 'GET',
    pattern: '/evidence/:id',
    auth: 'user',
    handler: async ({ user, db, admin, params }) => {
      // Find item
      const { data: item } = await db
        .from('evidence_items')
        .select('*, cases!inner(owner_id)')
        .eq('id', params.id)
        .single();

      if (!item || (item.cases as any)?.owner_id !== user.id) {
        return new Response(
          JSON.stringify({ error: { code: 'NOT_FOUND', message: `Evidence ${params.id} not found` } }),
          { status: 404, headers: { 'Content-Type': 'application/json' } }
        );
      }

      // Fetch artifacts and segments
      const { data: artifacts } = await db
        .from('evidence_artifacts')
        .select('*')
        .eq('evidence_id', params.id);

      const { data: segments } = await db
        .from('evidence_segments')
        .select('*')
        .eq('evidence_id', params.id)
        .order('ordinal', { ascending: true });

      // Audit read of extracted content (§9.3 & §16)
      await admin.from('audit_events').insert({
        case_id: item.case_id,
        actor_type: 'USER',
        actor_id: user.id,
        entity_type: 'EVIDENCE',
        entity_id: item.id,
        action: 'EVIDENCE_VIEWED',
        metadata: { kind: 'CONTENT', displayId: item.display_id },
      });

      return {
        item,
        artifacts: artifacts || [],
        segments: segments || [],
      };
    },
  },

  // Audited Signed-URL Download flow (Spec §5.2, Regression T11, T12)
  {
    method: 'GET',
    pattern: '/evidence/:id/download',
    auth: 'user',
    handler: async ({ user, db, admin, params }) => {
      // 1. Authorize: user owns the case
      const { data: item } = await db
        .from('evidence_items')
        .select('*, cases!inner(owner_id)')
        .eq('id', params.id)
        .single();

      if (!item || (item.cases as any)?.owner_id !== user.id) {
        return new Response(
          JSON.stringify({ error: { code: 'NOT_FOUND', message: `Evidence ${params.id} not found` } }),
          { status: 404, headers: { 'Content-Type': 'application/json' } }
        );
      }

      // 2. Refuse if deleted or quarantined
      if (item.deleted_at || item.processing_status === 'QUARANTINED') {
        return new Response(
          JSON.stringify({
            error: {
              code: 'EVIDENCE_QUARANTINED',
              message: 'Evidence is quarantined or deleted; download refused.',
            },
          }),
          { status: 409, headers: { 'Content-Type': 'application/json' } }
        );
      }

      const ttlSeconds = parseInt(process.env.SIGNED_URL_TTL_SECONDS || '60', 10);

      // 3. Fail-closed: Write EVIDENCE_DOWNLOAD_AUTHORIZED first
      const { data: authEvent, error: authAuditErr } = await admin
        .from('audit_events')
        .insert({
          case_id: item.case_id,
          actor_type: 'USER',
          actor_id: user.id,
          entity_type: 'EVIDENCE',
          entity_id: item.id,
          action: 'EVIDENCE_DOWNLOAD_AUTHORIZED',
          metadata: { displayId: item.display_id },
        })
        .select()
        .single();

      if (authAuditErr || !authEvent) {
        throw new Error('Audit authorization write failed; download aborted (fail-closed).');
      }

      // 4. Create signed URL with service role
      const { data: signData, error: signError } = await admin.storage
        .from('evidence')
        .createSignedUrl(item.storage_path, ttlSeconds);

      if (signError || !signData?.signedUrl) {
        throw new Error(`Failed to generate signed download URL: ${signError?.message}`);
      }

      // 5. Fail-closed: Write EVIDENCE_DOWNLOAD_URL_ISSUED before returning
      const { error: issueAuditErr } = await admin.from('audit_events').insert({
        case_id: item.case_id,
        actor_type: 'USER',
        actor_id: user.id,
        entity_type: 'EVIDENCE',
        entity_id: item.id,
        action: 'EVIDENCE_DOWNLOAD_URL_ISSUED',
        metadata: {
          authorizedEventId: authEvent.id,
          ttlSeconds,
          displayId: item.display_id,
        },
      });

      if (issueAuditErr) {
        throw new Error('Audit issuance write failed; URL discarded (fail-closed).');
      }

      const expiresAt = new Date(Date.now() + ttlSeconds * 1000).toISOString();
      return {
        url: signData.signedUrl,
        expiresAt,
      };
    },
  },
];


